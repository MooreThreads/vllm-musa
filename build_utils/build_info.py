"""Record the MUSA archs of a native build for the runtime arch check."""

from __future__ import annotations

from collections.abc import Iterable
from pathlib import Path

BUILD_INFO_NAME = "_build_info.py"


def write_build_info(
    package_dir: Path, capabilities: Iterable[tuple[int, int]]
) -> Path:
    """Write ``_build_info.py`` with the built ``(major, minor)`` archs into ``package_dir``."""
    archs = tuple(sorted({(int(major), int(minor)) for major, minor in capabilities}))
    if not archs:
        raise ValueError("a native build targets at least one MUSA arch")
    path = Path(package_dir) / BUILD_INFO_NAME
    path.write_text(
        "# Generated by setup.py: the MUSA archs (major, minor) the native extensions target.\n"
        f"MUSA_ARCHS = {archs!r}\n"
    )
    return path
